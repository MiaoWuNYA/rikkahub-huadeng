/** 当前学年学期，如 2025-2026-1。 */
function defaultSemesterId() {
  var now = new Date();
  var y = now.getFullYear();
  // getMonth() 是 0 起算，所以这里 +1 对齐自然月
  var m = now.getMonth() + 1;
  if (m >= 8 && m <= 12) return y + '-' + (y + 1) + '-1';
  if (m === 1) return (y - 1) + '-' + y + '-1';
  return (y - 1) + '-' + y + '-2';
}

